"""edge_platform.stamp -- bit-exact pins (ported from trade-data tests/test_stamp_characterization.py).

The literals are trade-data's own: `02d9c5d5de3aa791` (the raw-payload pin), `369e1240967d1329` and
`3ef9037fa8d6bcf7` (its card_lifecycle seals, which are `fingerprint` over `canon`-ed values) were
generated by trade-data's pre-migration code, and the rest by trade-data origin/main's stamp.py on
these inputs. A failing pin is NEVER fixed by editing the literal: find what changed the
serialization (the CONTINUITY LAW, stamp.py's docstring)."""

from __future__ import annotations

import datetime as dt
import hashlib
from zoneinfo import ZoneInfo

import pytest

from edge_platform import stamp

CFG = {"b": 2, "a": [1, "x"], "c": {"n": None, "d": 1.5}}
ROW = {"sym": "SPY", "legs": [1, 2]}


def test_fingerprint_pins() -> None:
    assert stamp.fingerprint(ROW) == "02d9c5d5de3aa791"
    assert stamp.fingerprint(CFG) == "369e1240967d1329"
    assert stamp.fingerprint(CFG, n=64) == "369e1240967d1329c042b98c39e8cb87e54566119e1965d70ce213cefc690361"


def test_sha_is_plain_truncated_sha256() -> None:
    assert stamp.sha("x") == hashlib.sha256(b"x").hexdigest()[:16] == "2d711642b726b044"
    assert len(stamp.sha("x", n=64)) == 64


def test_canon_pins_the_sealed_hash_inputs() -> None:
    et = ZoneInfo("America/New_York")
    d, ts = dt.date(2026, 11, 6), dt.datetime(2026, 11, 6, 14, 32, 7, tzinfo=et)
    cfg = {"unit_usd": 0.1 + 0.2, "day": d, "ts": ts, "n": 3, "tag": "x", "drift": 1.00000000004}
    canon = {k: stamp.canon(v) for k, v in cfg.items()}
    assert canon == {"unit_usd": 0.3, "day": "2026-11-06", "ts": "2026-11-06T14:32:07-05:00", "n": 3,
                     "tag": "x", "drift": 1.0}  # fmt: skip
    assert stamp.fingerprint(canon) == "3ef9037fa8d6bcf7"
    # the rounding is load-bearing: an 11th-decimal float64 wobble may not move a seal
    assert stamp.fingerprint({**canon, "drift": stamp.canon(1.0)}) == "3ef9037fa8d6bcf7"


def test_doc_sha_hashes_bytes_without_newline_normalization(tmp_path) -> None:
    crlf = bytes([13, 10])
    p = tmp_path / "doc.bin"
    p.write_bytes(b"line one" + crlf + b"line two" + bytes([10]))
    assert stamp.doc_sha(p) == "af28611c8dd7cdaa"
    p.write_bytes(b"line one" + bytes([10]) + b"line two" + bytes([10]))
    assert stamp.doc_sha(p) != "af28611c8dd7cdaa"


def test_git_sha_reads_the_variable_the_caller_names(monkeypatch) -> None:
    monkeypatch.delenv("BUILD_SHA", raising=False)
    assert stamp.git_sha("BUILD_SHA") is None
    assert stamp.git_sha("BUILD_SHA", short=True) is None
    monkeypatch.setenv("BUILD_SHA", "abcdef0123456789deadbeef")
    assert stamp.git_sha("BUILD_SHA") == "abcdef0123456789deadbeef"
    assert stamp.git_sha("BUILD_SHA", short=True) == "abcdef012345"
    monkeypatch.setenv("BUILD_SHA", "  ")
    assert stamp.git_sha("BUILD_SHA") is None


def test_git_sha_without_a_variable_name_refuses() -> None:
    with pytest.raises(ValueError, match="environment variable"):
        stamp.git_sha("")
